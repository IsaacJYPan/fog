from __future__ import annotations

import enum

# --- §1.8 Action indexing (fixed, size 14) --------------------------------------------------------
# The legality mask is computed each turn from the Showdown request JSON — never learned.


class ActionType(enum.IntEnum):
    MOVE = 0             # slots 0..3   : use move slot 1-4
    MOVE_TERA = 1        # slots 4..7   : use move slot 1-4 with Terastallization
    SWITCH = 2           # slots 8..12  : switch to party slot 1-5 (team order minus active)
    FORCED = 3           # slot 13      : <STRUGGLE/FORCED> (recharge / locked / single-option turns)


N_MOVES_PER_MON = 4
N_PARTY_SWITCH = 5
N_ACTIONS = 14

# Explicit index -> (type, sub-index) map. Party slot mapping is team-order-minus-active (fixed).
ACTIONS: list[tuple[ActionType, int]] = (
    [(ActionType.MOVE, i) for i in range(N_MOVES_PER_MON)]          # 0-3
    + [(ActionType.MOVE_TERA, i) for i in range(N_MOVES_PER_MON)]   # 4-7
    + [(ActionType.SWITCH, i) for i in range(N_PARTY_SWITCH)]       # 8-12
    + [(ActionType.FORCED, 0)]                                      # 13
)
assert len(ACTIONS) == N_ACTIONS

MOVE_SLOTS = range(0, 4)
MOVE_TERA_SLOTS = range(4, 8)
SWITCH_SLOTS = range(8, 13)
FORCED_SLOT = 13


